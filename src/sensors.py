def is_lower_is_worse(substance: str) -> bool:
    return substance in LOWER_IS_WORSE


def substance_lookup(category: str, substance: str) -> tuple[str, float] | None:
    """(단위, 임계값)을 찾는다. 물질명이 테이블에 없으면 None."""
    table, _ = CATEGORIES.get(category, ([], ""))
    for name, unit, threshold, _range in table:
        if name == substance:
            return unit, threshold
    return None


